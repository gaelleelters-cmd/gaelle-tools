/* Builds a self-contained Outlook sender (.vbs) — no Azure, no helper install. */
(function (global) {
  'use strict';

  function csvCell(v) {
    var s = String(v == null ? '' : v);
    if (/[",\n\r]/.test(s)) return '"' + s.replace(/"/g, '""') + '"';
    return s;
  }

  function toBase64Utf8(str) {
    return btoa(unescape(encodeURIComponent(str)));
  }

  function vbsAppendChunks(varName, text, chunkSize) {
    var size = chunkSize || 140;
    var out = [varName + ' = ""'];
    for (var i = 0; i < text.length; i += size) {
      out.push(varName + ' = ' + varName + ' & "' + text.substr(i, size) + '"');
    }
    return out.join('\r\n');
  }

  function buildCsv(mails) {
    var lines = ['FirstName,Email,AttachmentPath,CC,BCC,Subject,Message,Greeting,DisplayOnly'];
    mails.forEach(function (m) {
      lines.push([
        csvCell(m.first),
        csvCell(m.email),
        csvCell(m.attach || ''),
        csvCell(m.cc),
        csvCell(m.bcc),
        csvCell(m.subject || 'Document Attached'),
        csvCell(m.message),
        csvCell(m.greeting),
        csvCell('0')
      ].join(','));
    });
    return lines.join('\r\n');
  }

  function buildVbs(mails, attachment) {
    var csvB64 = toBase64Utf8(buildCsv(mails));
    var attachName = (attachment && attachment.name) ? String(attachment.name).replace(/[\\/:*?"<>|]/g, '_') : '';
    var attachB64 = (attachment && attachment.contentBytes) ? String(attachment.contentBytes) : '';

    return [
      "' Mail Mass — one-shot Outlook sender",
      "' Generated by gaelleelters.com — double-click to send from YOUR Outlook.",
      "' No install. No Microsoft app setup. Uses classic Outlook on this PC.",
      "' Self-contained: run it from any folder (Downloads, Desktop, USB).",
      '',
      'Option Explicit',
      '',
      'Dim OutlookApp, OutlookMail, inspector, fso, sh',
      'Dim csvText, allRows, cols, ri',
      'Dim firstName, emailAddr, attachPath, rowAttach, ccEmail, bccEmail, subjectText, messageText, greetingText',
      'Dim displayOnly, emailBody, sentCount, skippedCount',
      'Dim csvB64, attachB64, attachName, tempDir, tempCsv, tempAttach, bytes',
      '',
      'Set fso = CreateObject("Scripting.FileSystemObject")',
      'Set sh = CreateObject("WScript.Shell")',
      'Randomize',
      'tempDir = fso.BuildPath(sh.ExpandEnvironmentStrings("%TEMP%"), "MailMass_" & Year(Now) & Right("0" & Month(Now), 2) & Right("0" & Day(Now), 2) & "_" & Right("0" & Hour(Now), 2) & Right("0" & Minute(Now), 2) & Right("0" & Second(Now), 2) & "_" & Int(Rnd * 9000 + 1000))',
      'If Not fso.FolderExists(tempDir) Then fso.CreateFolder tempDir',
      '',
      vbsAppendChunks('csvB64', csvB64),
      vbsAppendChunks('attachB64', attachB64),
      'attachName = "' + attachName.replace(/"/g, '') + '"',
      '',
      'tempCsv = fso.BuildPath(tempDir, "mails.csv")',
      'WriteUtf8File tempCsv, DecodeBase64ToString(csvB64)',
      '',
      'attachPath = ""',
      'If Len(attachB64) > 0 And Len(attachName) > 0 Then',
      '  tempAttach = fso.BuildPath(tempDir, attachName)',
      '  WriteBinaryFile tempAttach, DecodeBase64ToBytes(attachB64)',
      '  attachPath = tempAttach',
      'End If',
      '',
      'On Error Resume Next',
      'Set OutlookApp = GetObject(, "Outlook.Application")',
      'If OutlookApp Is Nothing Then Set OutlookApp = CreateObject("Outlook.Application")',
      'On Error GoTo 0',
      'If OutlookApp Is Nothing Then',
      '  MsgBox "Could not start Outlook. Open Outlook and try again.", vbCritical, "Mail Mass"',
      '  WScript.Quit 1',
      'End If',
      '',
      'csvText = ReadUtf8File(tempCsv)',
      'If Left(csvText, 1) = ChrW(&HFEFF) Then csvText = Mid(csvText, 2)',
      'Set allRows = ParseCsvRecords(csvText)',
      'sentCount = 0',
      'skippedCount = 0',
      '',
      'For ri = 0 To allRows.Count - 1',
      '  If ri > 0 Then',
      '    cols = allRows(ri)',
      '    firstName = GetCol(cols, 0)',
      '    emailAddr = GetCol(cols, 1)',
      '    rowAttach = GetCol(cols, 2)',
      '    If rowAttach = "" Then rowAttach = attachPath',
      '    ccEmail = GetCol(cols, 3)',
      '    bccEmail = GetCol(cols, 4)',
      '    subjectText = GetCol(cols, 5)',
      '    messageText = GetCol(cols, 6)',
      '    greetingText = GetCol(cols, 7)',
      '    displayOnly = GetCol(cols, 8)',
      '    If subjectText = "" Then subjectText = "Document Attached"',
      '    If emailAddr = "" Then',
      '      skippedCount = skippedCount + 1',
      '    Else',
      '      Set OutlookMail = OutlookApp.CreateItem(0)',
      '      OutlookMail.BodyFormat = 2',
      '      Set inspector = OutlookMail.GetInspector',
      '      WScript.Sleep 200',
      '      emailBody = BuildMessageHtml(greetingText, firstName, messageText)',
      '      OutlookMail.HTMLBody = InsertIntoBody(OutlookMail.HTMLBody, emailBody)',
      '      OutlookMail.To = emailAddr',
      '      If ccEmail <> "" Then OutlookMail.CC = ccEmail',
      '      If bccEmail <> "" Then OutlookMail.BCC = bccEmail',
      '      OutlookMail.Subject = subjectText',
      '      If rowAttach <> "" Then OutlookMail.Attachments.Add rowAttach',
      '      On Error Resume Next',
      '      inspector.Close 0',
      '      On Error GoTo 0',
      '      Set inspector = Nothing',
      // Block If required: "If x Then obj.NoArgMethod Else ..." is a VBScript
      // compile error when the method before Else takes no arguments.
      '      If displayOnly = "0" Then',
      '        OutlookMail.Send',
      '      Else',
      '        OutlookMail.Display',
      '      End If',
      '      Set OutlookMail = Nothing',
      '      sentCount = sentCount + 1',
      '      WScript.Sleep 400',
      '    End If',
      '  End If',
      'Next',
      '',
      'On Error Resume Next',
      'fso.DeleteFolder tempDir, True',
      'On Error GoTo 0',
      '',
      'MsgBox "Done." & vbCrLf & "Sent: " & sentCount & vbCrLf & "Skipped: " & skippedCount, vbInformation, "Mail Mass"',
      '',
      'Function DecodeBase64ToBytes(b64)',
      '  Dim xml, node',
      '  Set xml = CreateObject("MSXML2.DOMDocument.6.0")',
      '  Set node = xml.createElement("b64")',
      '  node.dataType = "bin.base64"',
      '  node.text = b64',
      '  DecodeBase64ToBytes = node.nodeTypedValue',
      'End Function',
      '',
      'Function DecodeBase64ToString(b64)',
      '  Dim stm',
      '  Set stm = CreateObject("ADODB.Stream")',
      '  stm.Type = 1',
      '  stm.Open',
      '  stm.Write DecodeBase64ToBytes(b64)',
      '  stm.Position = 0',
      '  stm.Type = 2',
      '  stm.Charset = "utf-8"',
      '  DecodeBase64ToString = stm.ReadText',
      '  stm.Close',
      'End Function',
      '',
      'Sub WriteBinaryFile(path, bytes)',
      '  Dim stm',
      '  Set stm = CreateObject("ADODB.Stream")',
      '  stm.Type = 1',
      '  stm.Open',
      '  stm.Write bytes',
      '  If fso.FileExists(path) Then fso.DeleteFile path, True',
      '  stm.SaveToFile path, 2',
      '  stm.Close',
      'End Sub',
      '',
      'Sub WriteUtf8File(path, text)',
      '  Dim stm',
      '  Set stm = CreateObject("ADODB.Stream")',
      '  stm.Type = 2',
      '  stm.Charset = "utf-8"',
      '  stm.Open',
      '  stm.WriteText text',
      '  If fso.FileExists(path) Then fso.DeleteFile path, True',
      '  stm.SaveToFile path, 2',
      '  stm.Close',
      'End Sub',
      '',
      'Function ReadUtf8File(path)',
      '  Dim stm',
      '  Set stm = CreateObject("ADODB.Stream")',
      '  stm.Type = 2',
      '  stm.Charset = "utf-8"',
      '  stm.Open',
      '  stm.LoadFromFile path',
      '  ReadUtf8File = stm.ReadText',
      '  stm.Close',
      'End Function',
      '',
      'Function BuildMessageHtml(greetingText, firstName, messageText)',
      '  Dim openLine, paras, i, html, p, t, isHtml',
      '  html = "<div style=\'font-family:Calibri,sans-serif;font-size:11.0pt;\'>"',
      '  If Trim(greetingText & "") <> "__SKIP__" Then',
      '    If Trim(greetingText & "") <> "" Then',
      '      openLine = HtmlEsc(greetingText) & " " & HtmlEsc(firstName) & ","',
      '    Else',
      '      openLine = HtmlEsc(firstName) & ","',
      '    End If',
      '    html = html & "<p class=MsoNormal style=\'margin:0 0 8pt 0;\'>" & openLine & "</p>"',
      '  End If',
      '  isHtml = False',
      '  If InStr(1, LCase(messageText & ""), "<") > 0 Then',
      '    If InStr(1, LCase(messageText & ""), "<span") > 0 Or InStr(1, LCase(messageText & ""), "<b") > 0 Or InStr(1, LCase(messageText & ""), "<i") > 0 Or InStr(1, LCase(messageText & ""), "<u") > 0 Or InStr(1, LCase(messageText & ""), "<p") > 0 Or InStr(1, LCase(messageText & ""), "<div") > 0 Or InStr(1, LCase(messageText & ""), "<br") > 0 Or InStr(1, LCase(messageText & ""), "<font") > 0 Then isHtml = True',
      '  End If',
      '  If isHtml Then',
      '    BuildMessageHtml = html & messageText & "</div>"',
      '    Exit Function',
      '  End If',
      '  t = Replace(Replace(messageText & "", vbCrLf, vbLf), vbCr, vbLf)',
      '  paras = Split(t, vbLf & vbLf)',
      '  For i = 0 To UBound(paras)',
      '    p = Trim(paras(i))',
      '    If p <> "" Then html = html & "<p class=MsoNormal style=\'margin:0 0 8pt 0;\'>" & Replace(HtmlEsc(p), vbLf, "<br>") & "</p>"',
      '  Next',
      '  BuildMessageHtml = html & "</div>"',
      'End Function',
      '',
      'Function InsertIntoBody(fullHtml, contentHtml)',
      '  Dim lower, pos, gt',
      '  If Trim(fullHtml & "") = "" Then InsertIntoBody = contentHtml : Exit Function',
      '  lower = LCase(fullHtml)',
      '  pos = InStr(1, lower, "<body")',
      '  If pos > 0 Then',
      '    gt = InStr(pos, fullHtml, ">")',
      '    If gt > 0 Then InsertIntoBody = Left(fullHtml, gt) & contentHtml & Mid(fullHtml, gt + 1) : Exit Function',
      '  End If',
      '  InsertIntoBody = contentHtml & fullHtml',
      'End Function',
      '',
      'Function ParseCsvRecords(text)',
      '  Dim rows, fields, i, ch, inQ, cur, allEmpty, fi',
      '  Set rows = CreateObject("Scripting.Dictionary")',
      '  Set fields = CreateObject("Scripting.Dictionary")',
      '  cur = "" : inQ = False',
      '  text = Replace(Replace(text, vbCrLf, vbLf), vbCr, vbLf)',
      '  For i = 1 To Len(text)',
      '    ch = Mid(text, i, 1)',
      '    If ch = """" Then',
      '      If inQ And i < Len(text) And Mid(text, i + 1, 1) = """" Then cur = cur & """" : i = i + 1 Else inQ = Not inQ',
      '    ElseIf ch = "," And Not inQ Then',
      '      fields.Add fields.Count, cur : cur = ""',
      '    ElseIf ch = vbLf And Not inQ Then',
      '      fields.Add fields.Count, cur',
      '      allEmpty = True',
      '      For fi = 0 To fields.Count - 1',
      '        If Trim(fields(fi) & "") <> "" Then allEmpty = False',
      '      Next',
      '      If Not allEmpty Then rows.Add rows.Count, DictToArray(fields)',
      '      Set fields = CreateObject("Scripting.Dictionary") : cur = ""',
      '    Else',
      '      cur = cur & ch',
      '    End If',
      '  Next',
      '  If cur <> "" Or fields.Count > 0 Then',
      '    fields.Add fields.Count, cur',
      '    allEmpty = True',
      '    For fi = 0 To fields.Count - 1',
      '      If Trim(fields(fi) & "") <> "" Then allEmpty = False',
      '    Next',
      '    If Not allEmpty Then rows.Add rows.Count, DictToArray(fields)',
      '  End If',
      '  Set ParseCsvRecords = rows',
      'End Function',
      '',
      'Function DictToArray(dict)',
      '  Dim arr(), i',
      '  If dict.Count = 0 Then ReDim arr(0) : arr(0) = "" : DictToArray = arr : Exit Function',
      '  ReDim arr(dict.Count - 1)',
      '  For i = 0 To dict.Count - 1 : arr(i) = dict(i) : Next',
      '  DictToArray = arr',
      'End Function',
      '',
      'Function GetCol(arr, idx)',
      '  If IsArray(arr) Then If UBound(arr) >= idx Then GetCol = Trim(arr(idx) & "") : Exit Function',
      '  GetCol = ""',
      'End Function',
      '',
      'Function HtmlEsc(s)',
      '  Dim t : t = s & ""',
      '  t = Replace(t, "&", "&amp;")',
      '  t = Replace(t, "<", "&lt;")',
      '  t = Replace(t, ">", "&gt;")',
      '  t = Replace(t, """", "&quot;")',
      '  HtmlEsc = t',
      'End Function'
    ].join('\r\n');
  }

  function download(mails, attachment) {
    var vbs = buildVbs(mails, attachment);
    var blob = new Blob([vbs], { type: 'application/octet-stream' });
    var url = URL.createObjectURL(blob);
    var a = document.createElement('a');
    a.href = url;
    a.download = 'MailMass_Send_Now.vbs';
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(function () { URL.revokeObjectURL(url); }, 2000);
    return { processed: mails.length, skipped: 0, mode: 'oneshot' };
  }

  global.MailMassOneShot = { download: download };
})(window);
